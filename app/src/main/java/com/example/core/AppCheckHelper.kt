private const val TAG = "AppCheckInit"

// App Check contract keys defined by the Firebase SDK and AI Studio runtime harness.
internal const val DEBUG_TOKEN_EXTRA = "FIREBASE_APPCHECK_DEBUG_TOKEN"
internal const val DEBUG_STORE_PREFIX = "com.google.firebase.appcheck.debug.store."
internal const val DEBUG_SECRET_KEY = "com.google.firebase.appcheck.debug.DEBUG_SECRET"
private const val RECAPTCHA_SITE_KEY_RES = "recaptcha_site_key"

// Internal metadata store to distinguish an explicitly registered debug token (from harness Intent)
// from an unregistered random UUID auto-generated by the Firebase Debug SDK on standalone phones.
internal const val APPCHECK_META_PREFS = "gosala_appcheck_meta"
internal const val META_EXPLICIT_DEBUG_TOKEN_KEY = "explicit_debug_token"

// Firebase App Check returns a base64-encoded JSON {"error":...} dummy token when attestation fails.
private const val DUMMY_ERROR_TOKEN_PREFIX = "eyJlcnJvciI6"

internal enum class AppCheckProviderKind {
    NONE,
    DEBUG,
    RECAPTCHA
}

@Volatile
private var appCheckAppContext: Context? = null

@Volatile
internal var activeAppCheckProviderKind: AppCheckProviderKind = AppCheckProviderKind.NONE
    private set

@Volatile
internal var lastAppCheckDiagnostic: String? = null
    private set

/**
 * Returns a concise, user-safe diagnostic note describing the last App Check verification failure
 * (e.g., provider type and root cause category) so the UI can show actionable guidance with Retry.
 */
fun describeAppCheckDiagnostic(language: AppLanguage): String? {
    val diag = lastAppCheckDiagnostic?.trim().takeIf { !it.isNullOrBlank() } ?: return null
    val lower = diag.lowercase()
    return when {
        lower.contains("missing_recaptcha") -> if (language == AppLanguage.HINDI) {
            "कारण: reCAPTCHA साइट कुंजी उपलब्ध नहीं है।"
        } else {
            "Cause: reCAPTCHA site key is missing."
        }
        lower.contains("debug_unregistered") || (lower.contains("debug") && lower.contains("403")) -> if (language == AppLanguage.HINDI) {
            "कारण: Debug App Check टोकन Firebase में सत्यापित नहीं हुआ।"
        } else {
            "Cause: Debug App Check token is not registered in Firebase."
        }
        lower.contains("recaptcha") -> if (language == AppLanguage.HINDI) {
            "कारण: reCAPTCHA सत्यापन पूरा नहीं हो सका (Play Services/इंटरनेट जांचें)।"
        } else {
            "Cause: reCAPTCHA attestation did not complete (check Play Services & network)."
        }
        else -> if (language == AppLanguage.HINDI) {
            "विवरण: $diag"
        } else {
            "Details: $diag"
        }
    }
}

/**
 * Detects Android emulator / virtual device runtimes (including AVD, Genymotion, and Google Cloud
 * Cuttlefish / AI Studio Streaming Emulators) so Debug builds on emulators NEVER get downgraded
 * to reCAPTCHA Enterprise (which cannot attest virtualized devices).
 */
internal fun isAndroidEmulator(): Boolean {
    val fingerprint = Build.FINGERPRINT.orEmpty().lowercase()
    val model = Build.MODEL.orEmpty().lowercase()
    val manufacturer = Build.MANUFACTURER.orEmpty().lowercase()
    val brand = Build.BRAND.orEmpty().lowercase()
    val device = Build.DEVICE.orEmpty().lowercase()
    val product = Build.PRODUCT.orEmpty().lowercase()
    val hardware = Build.HARDWARE.orEmpty().lowercase()
    return isEmulatorBuildProperties(
        fingerprint = fingerprint,
        model = model,
        manufacturer = manufacturer,
        brand = brand,
        device = device,
        product = product,
        hardware = hardware
    )
}

internal fun isEmulatorBuildProperties(
    fingerprint: String,
    model: String,
    manufacturer: String,
    brand: String,
    device: String,
    product: String,
    hardware: String
): Boolean {
    val fp = fingerprint.lowercase()
    val mdl = model.lowercase()
    val mfg = manufacturer.lowercase()
    val br = brand.lowercase()
    val dev = device.lowercase()
    val prd = product.lowercase()
    val hw = hardware.lowercase()
    return fp.startsWith("generic") ||
        fp.startsWith("unknown") ||
        fp.contains("emulator") ||
        fp.contains("sdk_gphone") ||
        fp.contains("cuttlefish") ||
        fp.contains("aosp_cf") ||
        fp.contains("cf_x86") ||
        fp.contains("cf_arm") ||
        fp.contains("vsoc") ||
        mdl.contains("google_sdk") ||
        mdl.contains("emulator") ||
        mdl.contains("android sdk built for x86") ||
        mdl.contains("sdk_gphone") ||
        mdl.contains("cuttlefish") ||
        mdl.contains("aosp on") ||
        mfg.contains("genymotion") ||
        hw.contains("goldfish") ||
        hw.contains("ranchu") ||
        hw.contains("cutf") ||
        hw.contains("virtio") ||
        hw.contains("crosvm") ||
        hw.contains("qemu") ||
        dev.contains("vsoc") ||
        dev.contains("emu64") ||
        prd.contains("sdk_gphone") ||
        prd.contains("emulator") ||
        prd.contains("simulator") ||
        prd.contains("cuttlefish") ||
        prd.contains("aosp_cf") ||
        prd.contains("cf_x86") ||
        prd.contains("cf_arm") ||
        prd.contains("vsoc") ||
        prd.contains("vbox") ||
        (br.startsWith("generic") && dev.startsWith("generic"))
}

/**
 * Persists an explicitly registered Firebase App Check debug secret synchronously using commit()
 * BEFORE FirebaseAppCheck / DebugAppCheckProviderFactory reads SharedPreferences.
 */
@SuppressLint("ApplySharedPref")
internal fun persistDebugAppCheckToken(
    context: Context,
    persistenceKey: String,
    debugToken: String
): Boolean {
    val cleanToken = debugToken.trim()
    val debugPrefs = context.getSharedPreferences(
        "$DEBUG_STORE_PREFIX$persistenceKey",
        Context.MODE_PRIVATE
    )
    // CRITICAL: MUST use commit() instead of apply() so the secret is written synchronously
    // before DebugAppCheckProviderFactory reads SharedPreferences.
    val wroteDebugStore = debugPrefs.edit()
        .putString(DEBUG_SECRET_KEY, cleanToken)
        .commit()

    val metaPrefs = context.getSharedPreferences(APPCHECK_META_PREFS, Context.MODE_PRIVATE)
    metaPrefs.edit()
        .putString(META_EXPLICIT_DEBUG_TOKEN_KEY, cleanToken)
        .commit()

    return wroteDebugStore
}

/**
 * Clears any stale/unregistered random debug secret stored in SharedPreferences on standalone
 * physical phones. Never called for emulator / harness debug tokens.
 */
@SuppressLint("ApplySharedPref")
internal fun clearStoredDebugAppCheckToken(context: Context, persistenceKey: String) {
    context.getSharedPreferences("$DEBUG_STORE_PREFIX$persistenceKey", Context.MODE_PRIVATE)
        .edit()
        .remove(DEBUG_SECRET_KEY)
        .commit()
    context.getSharedPreferences(APPCHECK_META_PREFS, Context.MODE_PRIVATE)
        .edit()
        .remove(META_EXPLICIT_DEBUG_TOKEN_KEY)
        .commit()
}

/**
 * Resolves the provisioned reCAPTCHA Enterprise site key from resources safely.
 */
internal fun resolveRecaptchaSiteKey(context: Context): String? {
    val resId = context.resources.getIdentifier(
        RECAPTCHA_SITE_KEY_RES,
        "string",
        context.packageName
    )
    if (resId == 0) return null
    return runCatching { context.getString(resId).trim() }
        .getOrNull()
        ?.takeIf { it.isNotBlank() }
}

/**
 * Determines which App Check provider should be installed for the current launch:
 * - Release builds: ALWAYS RecaptchaAppCheckProviderFactory (reCAPTCHA Enterprise).
 * - Debug builds WITH explicit FIREBASE_APPCHECK_DEBUG_TOKEN in Intent:
 *   ALWAYS DebugAppCheckProviderFactory with the synchronously committed token.
 * - Debug builds on an Android Emulator (including Cuttlefish/AI Studio Streaming Emulator)
 *   OR with a previously saved explicit harness token:
 *   ALWAYS DebugAppCheckProviderFactory (never downgraded to reCAPTCHA on emulators).
 * - Standalone Debug APK on a real physical phone WITHOUT any harness debug token:
 *   RecaptchaAppCheckProviderFactory using the project's provisioned recaptcha_site_key so
 *   attestation succeeds with a real valid App Check JWT instead of an unregistered random UUID.
 */
internal fun decideAppCheckProviderKind(
    isDebugBuild: Boolean,
    intentDebugToken: String?,
    storedExplicitDebugToken: String?,
    storedSdkDebugSecret: String?,
    recaptchaSiteKey: String?,
    isEmulator: Boolean = isAndroidEmulator()
): AppCheckProviderKind {
    if (!isDebugBuild) {
        return if (!recaptchaSiteKey.isNullOrBlank()) AppCheckProviderKind.RECAPTCHA else AppCheckProviderKind.NONE
    }
    if (!intentDebugToken.isNullOrBlank()) {
        return AppCheckProviderKind.DEBUG
    }
    val hasValidExplicitCachedToken = !storedExplicitDebugToken.isNullOrBlank() &&
        storedExplicitDebugToken == storedSdkDebugSecret
    if (hasValidExplicitCachedToken || isEmulator) {
        return AppCheckProviderKind.DEBUG
    }
    return if (!recaptchaSiteKey.isNullOrBlank()) {
        AppCheckProviderKind.RECAPTCHA
    } else {
        AppCheckProviderKind.DEBUG
    }
}

/**
 * Configures Firebase App Check synchronously in MainActivity.onCreate() before setContent,
 * ViewModels, or any Firebase operations. Also safe to call from onNewIntent().
 */
fun configureAppCheck(context: Context, intent: Intent?) {
    try {
        val appContext = context.applicationContext ?: context
        appCheckAppContext = appContext

        // 1. Ensure FirebaseApp is initialized before touching App Check
        if (FirebaseApp.getApps(appContext).isEmpty()) {
            FirebaseApp.initializeApp(appContext)
        }
        val firebaseApp = FirebaseApp.getInstance()
        val persistenceKey = firebaseApp.persistenceKey
        val intentDebugToken = intent?.getStringExtra(DEBUG_TOKEN_EXTRA)?.trim()?.takeIf { it.isNotEmpty() }
        val recaptchaSiteKey = resolveRecaptchaSiteKey(appContext)
        val emulator = isAndroidEmulator()

        val metaPrefs = appContext.getSharedPreferences(APPCHECK_META_PREFS, Context.MODE_PRIVATE)
        val storedExplicitToken = metaPrefs.getString(META_EXPLICIT_DEBUG_TOKEN_KEY, null)?.trim()
        val storedSdkSecret = appContext.getSharedPreferences(
            "$DEBUG_STORE_PREFIX$persistenceKey",
            Context.MODE_PRIVATE
        ).getString(DEBUG_SECRET_KEY, null)?.trim()

        val targetKind = decideAppCheckProviderKind(
            isDebugBuild = BuildConfig.DEBUG,
            intentDebugToken = intentDebugToken,
            storedExplicitDebugToken = storedExplicitToken,
            storedSdkDebugSecret = storedSdkSecret,
            recaptchaSiteKey = recaptchaSiteKey,
            isEmulator = emulator
        )

        when (targetKind) {
            AppCheckProviderKind.DEBUG -> {
                // CRITICAL ORDER: Persist debug secret synchronously BEFORE calling FirebaseAppCheck.getInstance()
                if (!intentDebugToken.isNullOrEmpty()) {
                    val persisted = persistDebugAppCheckToken(appContext, persistenceKey, intentDebugToken)
                    Log.d(TAG, "App Check debug secret committed synchronously: $persisted")
                } else if (!storedExplicitToken.isNullOrEmpty() && storedSdkSecret != storedExplicitToken) {
                    // Restore previously saved explicit harness token if SDK prefs drifted
                    persistDebugAppCheckToken(appContext, persistenceKey, storedExplicitToken)
                    Log.d(TAG, "Restored saved explicit App Check debug secret synchronously.")
                } else {
                    Log.d(TAG, "Using DebugAppCheckProviderFactory (emulator=$emulator).")
                }
                val appCheck = FirebaseAppCheck.getInstance(firebaseApp)
                if (activeAppCheckProviderKind != AppCheckProviderKind.DEBUG || !intentDebugToken.isNullOrEmpty()) {
                    appCheck.installAppCheckProviderFactory(
                        DebugAppCheckProviderFactory.getInstance(),
                        /* isTokenAutoRefreshEnabled = */ true
                    )
                    activeAppCheckProviderKind = AppCheckProviderKind.DEBUG
                    lastAppCheckDiagnostic = null
                    Log.d(TAG, "DebugAppCheckProviderFactory installed with auto-refresh enabled.")
                }
            }
            AppCheckProviderKind.RECAPTCHA -> {
                // Only clear unregistered random debug secret on standalone physical-phone debug installs
                if (BuildConfig.DEBUG && !emulator && !storedSdkSecret.isNullOrEmpty() && storedExplicitToken.isNullOrEmpty()) {
                    clearStoredDebugAppCheckToken(appContext, persistenceKey)
                }
                val siteKey = recaptchaSiteKey
                if (!siteKey.isNullOrBlank()) {
                    val appCheck = FirebaseAppCheck.getInstance(firebaseApp)
                    if (activeAppCheckProviderKind != AppCheckProviderKind.RECAPTCHA) {
                        appCheck.installAppCheckProviderFactory(
                            RecaptchaAppCheckProviderFactory.getInstance(siteKey),
                            /* isTokenAutoRefreshEnabled = */ true
                        )
                        activeAppCheckProviderKind = AppCheckProviderKind.RECAPTCHA
                        lastAppCheckDiagnostic = null
                        Log.d(TAG, "RecaptchaAppCheckProviderFactory installed with auto-refresh enabled.")
                    }
                } else {
                    lastAppCheckDiagnostic = "missing_recaptcha_site_key"
                    Log.e(TAG, "recaptcha_site_key string resource not found or blank.")
                }
            }
            AppCheckProviderKind.NONE -> {
                lastAppCheckDiagnostic = "missing_recaptcha_site_key"
                Log.e(TAG, "No valid App Check provider could be configured (missing recaptcha_site_key).")
            }
        }
    } catch (e: Exception) {
        lastAppCheckDiagnostic = e.message?.take(120) ?: "init_failed"
        // Log explicitly to keep App Check attestation failures visible
        Log.e(TAG, "Failed to initialize Firebase App Check", e)
    }
}

/**
 * Checks whether an obtained App Check token string is a real non-empty JWT and NOT the
 * Firebase SDK dummy error placeholder token.
 */
internal fun isValidAppCheckJwt(token: String?): Boolean {
    if (token.isNullOrBlank()) return false
    if (token.startsWith(DUMMY_ERROR_TOKEN_PREFIX)) return false
    return token.count { it == '.' } >= 2
}

/**
 * Force-refreshes the active Firebase App Check token when an AI call encounters an App Check error.
 * Preserves the Debug provider and harness debug token on emulators; only upgrades to reCAPTCHA
 * Enterprise on standalone physical-phone debug builds that have no explicit harness token.
 */
suspend fun refreshAppCheckToken(forceRefresh: Boolean = true): Boolean {
    return try {
        val firebaseApp = FirebaseApp.getInstance()
        val ctx = appCheckAppContext ?: firebaseApp.applicationContext
        if (activeAppCheckProviderKind == AppCheckProviderKind.NONE) {
            configureAppCheck(ctx, null)
        }
        val appCheck = FirebaseAppCheck.getInstance(firebaseApp)
        val firstResult = runCatching { appCheck.getAppCheckToken(forceRefresh).await() }
        val firstToken = firstResult.getOrNull()?.token
        if (isValidAppCheckJwt(firstToken)) {
            lastAppCheckDiagnostic = null
            Log.d(TAG, "App Check token valid (provider=$activeAppCheckProviderKind, forceRefresh=$forceRefresh)")
            return true
        }

        val emulator = isAndroidEmulator()
        val storedExplicitToken = ctx.getSharedPreferences(APPCHECK_META_PREFS, Context.MODE_PRIVATE)
            .getString(META_EXPLICIT_DEBUG_TOKEN_KEY, null)
            ?.trim()
        val siteKey = resolveRecaptchaSiteKey(ctx)

        // NEVER overwrite Debug provider on an emulator or when an explicit harness debug token is registered.
        val canUpgradeToRecaptcha = !emulator &&
            storedExplicitToken.isNullOrBlank() &&
            activeAppCheckProviderKind != AppCheckProviderKind.RECAPTCHA &&
            !siteKey.isNullOrBlank()

        if (canUpgradeToRecaptcha) {
            Log.w(
                TAG,
                "App Check token invalid on standalone physical device; upgrading to RecaptchaAppCheckProviderFactory.",
                firstResult.exceptionOrNull()
            )
            clearStoredDebugAppCheckToken(ctx, firebaseApp.persistenceKey)
            appCheck.installAppCheckProviderFactory(
                RecaptchaAppCheckProviderFactory.getInstance(siteKey),
                /* isTokenAutoRefreshEnabled = */ true
            )
            activeAppCheckProviderKind = AppCheckProviderKind.RECAPTCHA

            val recovered = runCatching { appCheck.getAppCheckToken(true).await() }
            val recoveredValid = isValidAppCheckJwt(recovered.getOrNull()?.token)
            if (recoveredValid) {
                lastAppCheckDiagnostic = null
            } else {
                lastAppCheckDiagnostic = "recaptcha: ${recovered.exceptionOrNull()?.message?.take(100) ?: "invalid_token"}"
            }
            Log.d(TAG, "App Check recovery via reCAPTCHA Enterprise succeeded=$recoveredValid")
            return recoveredValid
        }

        val errMsg = firstResult.exceptionOrNull()?.message?.take(100)
        lastAppCheckDiagnostic = when (activeAppCheckProviderKind) {
            AppCheckProviderKind.DEBUG -> "debug_unregistered: ${errMsg ?: "invalid_token"}"
            AppCheckProviderKind.RECAPTCHA -> "recaptcha: ${errMsg ?: "invalid_token"}"
            AppCheckProviderKind.NONE -> "missing_recaptcha_site_key"
        }
        Log.w(
            TAG,
            "App Check token refresh did not return a valid JWT (provider=$activeAppCheckProviderKind, emulator=$emulator, diag=$lastAppCheckDiagnostic).",
            firstResult.exceptionOrNull()
        )
        false
    } catch (e: Exception) {
        lastAppCheckDiagnostic = "${activeAppCheckProviderKind.name.lowercase()}: ${e.message?.take(100) ?: "refresh_failed"}"
        Log.e(TAG, "App Check token refresh failed (forceRefresh=$forceRefresh)", e)
        false
    }
}

/**
 * Returns a safe, secret-free diagnostic summary of the current App Check configuration
 * (provider kind and build mode) for error logs. Never exposes any token or site key.
 */
fun describeAppCheckProviderForLog(): String {
    val provider = activeAppCheckProviderKind.name
    val mode = if (BuildConfig.DEBUG) "DEBUG" else "RELEASE"
    val diag = lastAppCheckDiagnostic?.take(60)
    return if (diag.isNullOrBlank()) {
        "AppCheck[mode=$mode,provider=$provider]"
    } else {
        "AppCheck[mode=$mode,provider=$provider,note=$diag]"
    }
}

/**
 * Identifies App Check / HTTP 401 / HTTP 403 attestation token errors so AI calls can refresh the
 * App Check token & retry once, while strictly excluding API-disabled / billing / invalid-key errors.
 */
fun isAppCheckTokenError(throwable: Throwable?): Boolean {
    val chainText = buildString {
        var current = throwable
        while (current != null) {
            append(current.javaClass.simpleName).append(' ')
            append(current.message.orEmpty()).append(' ')
            current = current.cause
        }
    }.lowercase()

    if (chainText.isBlank()) return false

    // Never misclassify API-disabled, billing, or invalid-API-key failures as App Check token errors
    val isExplicitApiOrBillingError =
        chainText.contains("service_disabled") ||
            chainText.contains("api has not been used") ||
            chainText.contains("not enabled") ||
            chainText.contains("api_key_invalid") ||
            chainText.contains("billing")
    if (isExplicitApiOrBillingError && !chainText.contains("app check") && !chainText.contains("appcheck")) {
        return false
    }

    return chainText.contains("app check") ||
        chainText.contains("appcheck") ||
        chainText.contains("attestation") ||
        chainText.contains("firebase app check token is invalid") ||
        chainText.contains("unauthenticated") ||
        chainText.contains("401") ||
        chainText.contains("403")
}

